"""Print independent fixed v1 vectors; never used to generate test expectations at runtime."""
from ECWire import N, k, pad, sha, derive, context, proofs

digest = bytes.fromhex('0123456789abcdef0123456789abcdef')
salt = bytes(range(16))
a, b = int.from_bytes(bytes(range(32)), 'big'), int.from_bytes(bytes(range(32,64)), 'big')
x = derive(digest, salt)
v, A = pow(5,x,N), pow(5,a,N)
B = (k*v+pow(5,b,N))%N
u = int.from_bytes(sha(pad(A)+pad(B)), 'big')
S = pow((B-k*pow(5,x,N))%N,a+u*x,N)
assert S == pow(A*pow(v,u,N)%N,b,N)
transcript = bytes(range(163))
m1,m2 = proofs(S, context(0,salt,transcript,A,B))
values = dict(x=x.to_bytes(32,'big'), v=pad(v), A=pad(A), B=pad(B), S=pad(S), m1=m1, m2=m2)
print('// Generated by GenerateECSRPVector.py using Python hashlib and integer arithmetic.')
print('// Fixed public test inputs only. Copyright (c) 2026 aMule Team. GPL-2.0-or-later.')
print('namespace V1Vector {')
for name,value in values.items():
    print(f'const char *{name} =')
    text=value.hex()
    for i in range(0,len(text),96): print('    "'+text[i:i+96]+'"')
    print(';')
print('}')
